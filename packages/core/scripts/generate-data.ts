function makeKey(raw: string) {
    const key = raw
        .toUpperCase()
        .replace(/ /g, '_')
        .replace(/@/g, '')
        .replace(/[^A-Z0-9_]/g, '_');
    return /^\d/.test(key) ? `_${key}` : key;
}

function simpleEntries<T>(items: T[], getName: (item: T) => string, getId: (item: T) => number): Entry[] {
    const used = new Set<string>();
    return items.map((item) => {
        const base = makeKey(getName(item));
        let name = base;
        for (let suffix = 2; used.has(name); suffix += 1) name = `${base}_${suffix}`;
        used.add(name);
        return { name, id: getId(item) };
    });
}

function abilityKey(ability: SC2APIProtocol.AbilityData) {
    const button = ability.buttonName || (ability.linkIndex === 0 ? ability.linkName : '');
    if (!button && !ability.remapsToAbilityId) return undefined;
    if (ability.friendlyName) return makeKey(ability.friendlyName);
    return button ? makeKey(`${ability.linkName}_${button}`) : undefined;
}

function abilityEntries(): Entry[] {
    const byName = new Map<string, SC2APIProtocol.AbilityData>();
    [...abilities]
        .sort((first, second) => first.abilityId! - second.abilityId!)
        .forEach((ability) => {
            const key = abilityKey(ability);
            if (!key) return;
            if (!byName.has(key) || ability.linkIndex === 0) byName.set(key, ability);
        });
    byName.set('SMART', abilityById.get(1) ?? { abilityId: 1 });
    return [...byName].map(([name, ability]) => ({
        name,
        id: ability.abilityId!,
        comment: TARGET_COMMENT[ability.target as number],
    }));
}

function parseConstants(source: string): NameIndex {
    const byName = new Map<string, number>();
    const byId = new Map<number, string>();
    for (const match of source.matchAll(/^export const ([A-Z0-9_]+) = (\d+);/gm)) {
        const id = Number(match[2]);
        byName.set(match[1], id);
        byId.set(id, match[1]);
    }
    return { byName, byId };
}

function formatConstant({ name, id, comment }: Entry) {
    return comment ? `export const ${name} = ${`${id};`.padEnd(7)}// ${comment}` : `export const ${name} = ${id};`;
}

type MergeReport = {
    file: ConstantFile;
    added: string[];
    idConflicts: string[];
    aliasesSkipped: string[];
    notGenerated: string[];
};

const nameIndexes = {} as Record<ConstantFile, NameIndex>;

function mergeConstantFile(file: ConstantFile, entries: Entry[]): MergeReport {
    const path = join(CONSTANTS_DIR, `${file}.ts`);
    const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
    const markerIndex = current.indexOf(MARKER);
    const hand = (markerIndex >= 0 ? current.slice(0, markerIndex) : current).replace(/\s*$/, '');
    const handIndex = parseConstants(hand);
    const generatedNames = new Set(entries.map((entry) => entry.name));

    const report: MergeReport = { file, added: [], idConflicts: [], aliasesSkipped: [], notGenerated: [] };
    const additions = entries
        .sort((first, second) => first.id - second.id || first.name.localeCompare(second.name))
        .filter((entry) => {
            const handId = handIndex.byName.get(entry.name);
            if (handId !== undefined) {
                if (handId !== entry.id)
                    report.idConflicts.push(`${entry.name}: kept ${handId}, data says ${entry.id}`);
                return false;
            }
            const handName = handIndex.byId.get(entry.id);
            if (handName !== undefined) {
                report.aliasesSkipped.push(`${entry.name} = ${entry.id} (already ${handName})`);
                return false;
            }
            report.added.push(entry.name);
            return true;
        });
    report.notGenerated = [...handIndex.byName.keys()].filter((name) => !generatedNames.has(name));

    const sections = [hand, additions.length > 0 ? [MARKER, ...additions.map(formatConstant)].join('\n') : ''].filter(
        (section) => section.length > 0,
    );
    writeFileSync(path, `${sections.join('\n\n')}\n`);

    nameIndexes[file] = parseConstants(readFileSync(path, 'utf8'));
    return report;
}

function writeNewConstantFile(file: ConstantFile, entries: Entry[]) {
    const lines = [...entries].sort((first, second) => first.id - second.id).map(formatConstant);
    writeFileSync(join(CONSTANTS_DIR, `${file}.ts`), `${HEADER}\n${lines.join('\n')}\n`);
    nameIndexes[file] = parseConstants(lines.join('\n'));
}

function unitAbilities(): Map<number, number[]> {
    const result = new Map<number, Set<number>>();
    const add = (unitTypeId: number, abilityIds: number[]) => {
        const set = result.get(unitTypeId) ?? new Set<number>();
        abilityIds.forEach((abilityId) => set.add(abilityId));
        result.set(unitTypeId, set);
    };

    Object.entries(typeAbilities).forEach(([unitTypeId, abilityIds]) => add(Number(unitTypeId), abilityIds));

    for (const fixture of readdirSync(FIXTURES_DIR)) {
        const dir = join(FIXTURES_DIR, fixture);
        if (!existsSync(join(dir, 'abilities.json'))) continue;
        const byLoop = readJson<Record<string, Record<string, number[]>>>(join(dir, 'abilities.json'));
        const latestByTag = new Map<string, { unitTypeId: number; abilityIds: number[] }>();
        Object.entries(byLoop)
            .sort(([first], [second]) => Number(first) - Number(second))
            .forEach(([loop, byTag]) => {
                const units =
                    readJson<SC2APIProtocol.ResponseObservation>(join(dir, `obs-${loop}.json`)).observation?.rawData
                        ?.units ?? [];
                const typeByTag = new Map(units.map((unit) => [unit.tag!, unit.unitType!]));
                Object.entries(byTag).forEach(([tag, abilityIds]) => {
                    const unitTypeId = typeByTag.get(tag);
                    if (unitTypeId !== undefined) latestByTag.set(tag, { unitTypeId, abilityIds });
                });
            });
        latestByTag.forEach(({ unitTypeId, abilityIds }) => add(unitTypeId, abilityIds));
    }

    return new Map(
        [...result]
            .filter(([, abilityIds]) => abilityIds.size > 0)
            .sort(([first], [second]) => first - second)
            .map(([unitTypeId, abilityIds]) => [unitTypeId, [...abilityIds].sort((first, second) => first - second)]),
    );
}

function producedUnits(): Map<number, number> {
    const unitByName = new Map(units.map((unit) => [unit.name!, unit.unitId!]));
    const produces = new Map<number, number>();

    units.forEach((unit) => {
        const ability = abilityById.get(unit.abilityId ?? 0);
        if (!ability) return;
        const verb = (ability.friendlyName ?? '').split(' ')[0];
        const producing =
            (PRODUCING_VERBS.has(verb) && !ADDON_NAME.test(unit.name!)) || ONE_WAY_MORPH_PRODUCTS.has(unit.name!);
        if (producing) produces.set(ability.abilityId!, unit.unitId!);
    });

    abilities.forEach((ability) => {
        const [verb, ...rest] = (ability.friendlyName ?? '').split(' ');
        const productName = rest.join(' ');
        const warpProduct = unitByName.get(productName);
        if (verb === 'TrainWarp' && warpProduct !== undefined) produces.set(ability.abilityId!, warpProduct);

        const morphProduct = [productName, `${productName}MP`].find((name) => ONE_WAY_MORPH_PRODUCTS.has(name));
        if (MORPH_VERBS.has(verb) && morphProduct) produces.set(ability.abilityId!, unitByName.get(morphProduct)!);
    });

    return produces;
}

function trainedFrom(abilitiesByUnit: Map<number, number[]>) {
    const produces = producedUnits();
    const productsByLink = new Map<string, number[]>();
    produces.forEach((product, abilityId) => {
        const link = abilityById.get(abilityId)?.linkName ?? '';
        productsByLink.set(link, [...(productsByLink.get(link) ?? []), product]);
    });

    const result = new Map<number, Set<number>>();
    const addProducer = (product: number, producer: number) =>
        result.set(product, (result.get(product) ?? new Set()).add(producer));
    abilitiesByUnit.forEach((abilityIds, producer) => {
        abilityIds
            .filter((abilityId) => produces.has(abilityId))
            .flatMap((abilityId) => productsByLink.get(abilityById.get(abilityId)?.linkName ?? '') ?? [])
            .forEach((product) => addProducer(product, producer));
    });
    Object.entries(TRAINED_FROM_SUPPLEMENT).forEach(([product, producers]) => {
        producers.forEach((producer) => addProducer(unitIdByName(product), unitIdByName(producer)));
    });
    NOT_TRAINED.forEach((product) => result.delete(unitIdByName(product)));
    return new Map(
        [...result]
            .sort(([first], [second]) => first - second)
            .map(([product, producers]) => [product, [...producers].sort((first, second) => first - second)]),
    );
}

function researchedFrom(abilitiesByUnit: Map<number, number[]>) {
    const linkName = (abilityId: number) => abilityById.get(abilityId)?.linkName;
    const result = new Map<number, number>();
    const researchers = [...abilitiesByUnit]
        .filter(([unitTypeId]) => unitById.get(unitTypeId)?.name !== GENERIC_TECHLAB)
        .sort(([first], [second]) => first - second);

    [...upgrades]
        .sort((first, second) => first.upgradeId! - second.upgradeId!)
        .forEach((upgrade) => {
            const abilityId = researchRequirements[upgrade.upgradeId!]?.ability ?? upgrade.abilityId;
            if (!abilityId || NOT_RESEARCHED.has(upgrade.name!)) return;
            const upgradeLink = linkName(abilityId);
            const researcher =
                researchers.find(([, abilityIds]) => abilityIds.includes(abilityId))?.[0] ??
                (abilityById.get(abilityId)?.available && upgradeLink && RESEARCHER_BY_LINK[upgradeLink]
                    ? unitIdByName(RESEARCHER_BY_LINK[upgradeLink])
                    : researchers.find(([, abilityIds]) =>
                          abilityIds.some((abilityId) => linkName(abilityId) === upgradeLink),
                      )?.[0]);
            if (researcher !== undefined) result.set(upgrade.upgradeId!, researcher);
        });
    return result;
}

const reference = (file: ConstantFile, namespace: string) => (id: number) => {
    const name = nameIndexes[file].byId.get(id);
    return name ? `${namespace}.${name}` : String(id);
};

function writeDict(
    fileName: string,
    exportName: string,
    imports: [ConstantFile, string][],
    valueType: string,
    rows: string[],
) {
    const importLines = imports.map(([file, namespace]) => `import * as ${namespace} from '../${file}.ts';`);
    const body = rows.map((row) => `    ${row},`).join('\n');
    const source = [
        HEADER,
        ...importLines,
        '',
        `export const ${exportName}: Record<number, ${valueType}> = {`,
        body,
        '};',
        '',
    ].join('\n');
    writeFileSync(join(DICTS_DIR, `${fileName}.ts`), source);
    return rows.length;
}

function printReport(report: MergeReport) {
    console.log(`\n${report.file}.ts: +${report.added.length} names`);
    console.log(`  id conflicts (existing kept): ${report.idConflicts.length}`);
    report.idConflicts.forEach((line) => console.log(`    ${line}`));
    console.log(`  aliases skipped (id already named): ${report.aliasesSkipped.length}`);
    report.aliasesSkipped.forEach((line) => console.log(`    ${line}`));
    console.log(`  existing names the generator would not produce: ${report.notGenerated.length}`);
    if (report.notGenerated.length > 0) console.log(`    ${report.notGenerated.join(', ')}`);
}

